"""The USR-keyed graph: components, caller attribution, the fixpoint and the buckets."""

from __future__ import annotations

from typing import TYPE_CHECKING

from deadweight.analysis import (
    analyze,
    annotate_prod_mentions,
    build_components,
    definition_spans,
    enclosing_function,
    is_dispatch_root,
)
from deadweight.model import STATUS_ERROR, STATUS_OK, Decl, Facts, Loc, Ref, Span

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path

PROD_ROOTS = ("client", "logging")
TEST_ROOTS = ("tests",)

USR_GET = "c:@N@topi@S@Widget@F@Get#1"
USR_RUN = "c:@N@topi@S@Widget@F@Run#"
USR_HELPER = "c:@N@topi@S@Widget@F@Helper#"
USR_TEST_ONLY = "c:@N@topi@F@TestOnly#"
USR_CASCADED = "c:@N@topi@F@Cascaded#"
USR_DEAD = "c:@N@topi@F@Dead#"
USR_USED = "c:@N@topi@F@Used#"
USR_CTOR = "c:@N@topi@S@Config@F@Config#"
USR_DTOR = "c:@N@topi@S@Config@F@~Config#"
USR_CONV = "c:@N@topi@S@Config@F@operator bool#1"
USR_ASSIGN = "c:@N@topi@S@Config@F@operator=#&1$@N@topi@S@Config#"
USR_MAIN = "c:@F@main#"
USR_SUBSCRIBE = "c:@N@topi@F@Subscribe#I#"
USR_OUTER = "c:@N@topi@F@Outer#"
USR_INNER = "c:@N@topi@F@Inner#"


def make_decl(  # noqa: PLR0913 -- a fixture builder: one argument per Decl field
    usr: str,
    name: str,
    *,
    file: str = "client/a.cpp",
    line: int = 1,
    kind: str = "function",
    markers: tuple[str, ...] = (),
    end_line: int | None = None,
) -> Decl:
    """One recorded declaration, with a body four lines long by default."""
    start = Loc(file=file, line=line, col=1)
    end = Loc(file=file, line=line + 4 if end_line is None else end_line, col=1)
    return Decl(
        usr=usr,
        kind=kind,
        name=name,
        file=file,
        loc=start,
        span=Span(start=start, end=end),
        markers=frozenset(markers),
        type_text="void ()",
    )


def make_ref(usr: str, *, tu: str = "tests/unit/t.cpp", line: int = 5) -> Ref:
    """One reference site inside the translation unit ``tu``."""
    return Ref(usr=usr, file=tu, loc=Loc(file=tu, line=line, col=3))


def make_facts(
    *,
    tu: str = "client/a.cpp",
    decls: Sequence[Decl] = (),
    refs: Sequence[Ref] = (),
    status: str = STATUS_OK,
    diags: Sequence[str] = (),
) -> Facts:
    """One translation unit's facts record."""
    return Facts(
        tu=tu,
        status=status,
        compiler={"libclang": "22.1.8"},
        decls=list(decls),
        refs=list(refs),
        diags=list(diags),
    )


def test_redeclarations_merge_by_usr() -> None:
    """A header declaration and its out-of-line definition are one function."""
    header = make_decl(USR_GET, "Get", file="client/widget.hpp", line=11)
    definition = make_decl(USR_GET, "Get", file="client/widget.cpp", line=126)
    components = build_components([header, definition], PROD_ROOTS)
    assert list(components) == [USR_GET]
    assert components[USR_GET].names == {"Get"}
    # The production declaration is the one the report quotes.
    assert components[USR_GET].decls == [definition, header]
    analysis = analyze(
        [make_facts(decls=[header, definition], refs=[make_ref(USR_GET)])],
        PROD_ROOTS,
        TEST_ROOTS,
    )
    assert [candidate.name for candidate in analysis.candidates] == ["Get"]
    assert analysis.candidates[0].file == "client/widget.cpp"


def test_shared_anchor_is_ambiguous() -> None:
    """Two functions generated by one macro share a definition anchor."""
    anchor = Loc(file="client/macros.hpp", line=7, col=8)
    span = Span(start=anchor, end=Loc(file="client/macros.hpp", line=9, col=3))
    twins = [
        Decl(
            usr=f"c:@N@topi@F@{name}#",
            kind="function",
            name=name,
            file="client/macros.hpp",
            loc=anchor,
            span=span,
            markers=frozenset(),
            type_text="void ()",
        )
        for name in ("MakeA", "MakeB")
    ]
    analysis = analyze([make_facts(decls=twins)], PROD_ROOTS, TEST_ROOTS)
    assert {candidate.name for candidate in analysis.ambiguous} == {"MakeA", "MakeB"}
    assert analysis.candidates == []
    assert analysis.dead_anywhere == []


def test_virtual_is_dispatch_root_and_keeper() -> None:
    """A virtual with test callers is a keeper, and its body keeps its callees live."""
    run = make_decl(USR_RUN, "Run", line=20, kind="method", markers=("virtual",))
    helper = make_decl(USR_HELPER, "Helper", line=40, kind="method")
    facts = make_facts(
        decls=[run, helper],
        refs=[
            make_ref(USR_HELPER, tu="client/impl.cpp", line=21),
            make_ref(USR_RUN, tu="tests/unit/t.cpp", line=5),
        ],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    assert is_dispatch_root(analysis.components[USR_RUN])
    assert [keeper.name for keeper in analysis.keepers] == ["Run"]
    assert analysis.candidates == []
    assert analysis.dead_anywhere == []


def test_cascade_names_the_prod_caller() -> None:
    """A helper reached only through a test-only function is test-only too."""
    facts = make_facts(
        decls=[
            make_decl(USR_TEST_ONLY, "TestOnly", line=40),
            make_decl(USR_CASCADED, "Cascaded", line=60),
        ],
        refs=[
            make_ref(USR_TEST_ONLY, line=5),
            make_ref(USR_CASCADED, tu="client/a.cpp", line=41),
        ],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    assert {candidate.name for candidate in analysis.candidates} == {
        "TestOnly",
        "Cascaded",
    }
    cascaded = next(item for item in analysis.candidates if item.name == "Cascaded")
    assert cascaded.reached_via == ["TestOnly"]
    direct = analyze([facts], PROD_ROOTS, TEST_ROOTS, cascade=False)
    assert [candidate.name for candidate in direct.candidates] == ["TestOnly"]
    assert direct.candidates[0].reached_via == []


def test_dead_anywhere_is_separate_from_test_only() -> None:
    """Nothing reaches one function and only tests reach the other."""
    facts = make_facts(
        decls=[
            make_decl(USR_DEAD, "Dead", line=20),
            make_decl(USR_USED, "Used", line=40),
        ],
        refs=[make_ref(USR_USED)],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    assert [candidate.name for candidate in analysis.candidates] == ["Used"]
    assert [candidate.name for candidate in analysis.dead_anywhere] == ["Dead"]
    assert analysis.dead_anywhere[0].test_refs == []


def test_special_members_are_never_candidates() -> None:
    """Construction, destruction, conversion and assignment are a human decision."""
    decls = [
        make_decl(USR_CTOR, "Config", line=40, kind="constructor"),
        make_decl(USR_DTOR, "~Config", line=45, kind="destructor"),
        make_decl(USR_CONV, "operator bool", line=50, kind="conversion"),
        make_decl(USR_ASSIGN, "operator=", line=55, kind="assignment"),
    ]
    facts = make_facts(
        decls=decls,
        refs=[make_ref(item.usr, line=5) for item in decls],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    assert analysis.candidates == []
    assert {candidate.kind for candidate in analysis.special_members} == {
        "constructor",
        "destructor",
        "conversion",
        "assignment",
    }


def test_main_is_an_entry_point() -> None:
    """``main`` is reached by the C runtime, so it is never dead weight."""
    analysis = analyze(
        [
            make_facts(
                decls=[make_decl(USR_MAIN, "main", file="client/main.cpp", line=5)],
            ),
        ],
        PROD_ROOTS,
        TEST_ROOTS,
    )
    assert [candidate.name for candidate in analysis.entry_points] == ["main"]
    assert analysis.dead_anywhere == []
    assert analysis.entry_points[0].reason.startswith("entry point")


def test_prod_mentions_catches_template_bodies(tmp_path: Path) -> None:
    """The graph cannot see a name used in a template body; a text search can."""
    registry = tmp_path / "client" / "registry.hpp"
    registry.parent.mkdir()
    registry.write_text(
        "template <typename Handler>\n"
        "void Register(Handler handler) { handler.Subscribe(); }\n",
        encoding="utf-8",
    )
    (tmp_path / "client" / "a.cpp").write_text(
        "int Subscribe(int value) { return value; }\n", encoding="utf-8",
    )
    facts = make_facts(
        decls=[make_decl(USR_SUBSCRIBE, "Subscribe", line=1)],
        refs=[make_ref(USR_SUBSCRIBE)],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    annotate_prod_mentions(analysis, tmp_path, PROD_ROOTS)
    # Relative to the scan root, like every other path in the report.
    assert analysis.candidates[0].prod_mentions == ["client/registry.hpp"]


def test_header_defined_flag_covers_c_headers() -> None:
    """A body that lives in a plain ``.h`` is still a header body."""
    facts = make_facts(
        decls=[make_decl(USR_HELPER, "Helper", file="client/widget.h", line=7)],
        refs=[make_ref(USR_HELPER)],
    )
    analysis = analyze([facts], PROD_ROOTS, TEST_ROOTS)
    assert analysis.candidates[0].flags == ["header-defined"]


def test_enclosing_function_picks_the_innermost_definition() -> None:
    """A reference inside a nested body belongs to the innermost function."""
    outer = make_decl(USR_OUTER, "Outer", line=10, end_line=30)
    inner = make_decl(USR_INNER, "Inner", line=20, end_line=25)
    spans = definition_spans(build_components([outer, inner], PROD_ROOTS), PROD_ROOTS)
    assert enclosing_function(spans, Loc(file="client/a.cpp", line=5, col=1)) is None
    innermost = enclosing_function(spans, Loc(file="client/a.cpp", line=22, col=1))
    assert innermost is not None
    assert innermost.name == "Inner"
    outermost = enclosing_function(spans, Loc(file="client/a.cpp", line=15, col=1))
    assert outermost is not None
    assert outermost.name == "Outer"


def test_a_failed_translation_unit_contributes_nothing_and_is_counted() -> None:
    """A unit that did not parse is reported, never silently dropped."""
    broken = make_facts(
        tu="client/broken.cpp",
        status=STATUS_ERROR,
        diags=["client/broken.cpp:1:1: error: expected ';'"],
    )
    parsed = make_facts(
        decls=[make_decl(USR_MAIN, "main", file="client/main.cpp", line=5)],
    )
    analysis = analyze([broken, parsed], PROD_ROOTS, TEST_ROOTS)
    assert analysis.tu_counts == {"prod": 1, "test": 0, "other": 0, "failed": 1}
    assert analysis.failures == [
        {
            "file": "client/broken.cpp",
            "reason": "client/broken.cpp:1:1: error: expected ';'",
        },
    ]
    assert [candidate.name for candidate in analysis.entry_points] == ["main"]
